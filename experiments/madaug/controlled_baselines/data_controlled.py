import torch
from torch.utils.data import DataLoader
from torchvision import datasets

from data.datasets import get_static_transforms
from experiments.madaug.make_split import load_split


def get_controlled_cifar100_loaders(
    root: str = "./data/raw",
    batch_size: int = 128,
    split_file: str = None,  # [controlled]
    train_transform=None,
    test_transform=None,
    num_workers: int = 4,
    debug: bool = False,
):

    if train_transform is None or test_transform is None:
        train_transform, test_transform = get_static_transforms("cifar100")

    # Download datasets

    full_train_dataset = datasets.CIFAR100(
        root, train=True, download=True, transform=train_transform
    )
    full_val_dataset = datasets.CIFAR100(
        root, train=True, download=True, transform=test_transform
    )
    test_dataset = datasets.CIFAR100(
        root, train=False, download=True, transform=test_transform
    )

    # [controlled] fixed stratified 49k/1k split shared with MADAug
    train_idx, val_idx = load_split(split_file)
    train_dataset = torch.utils.data.Subset(full_train_dataset, train_idx)
    val_dataset = torch.utils.data.Subset(full_val_dataset, val_idx)

    if debug:
        train_dataset = torch.utils.data.Subset(train_dataset, range(512))
        val_dataset = (
            torch.utils.data.Subset(val_dataset, range(128)) if val_dataset else None
        )
        test_dataset = torch.utils.data.Subset(test_dataset, range(128))

    pin_memory = torch.cuda.is_available()
    persistent = num_workers > 0
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=pin_memory,
        persistent_workers=persistent,
        drop_last=True,
    )
    val_loader = (
        DataLoader(
            val_dataset,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=pin_memory,
            persistent_workers=persistent,
        )
        if val_dataset
        else None
    )
    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=pin_memory,
        persistent_workers=persistent,
    )

    val_str = f"{len(val_dataset):,}" if val_dataset else "none (full-train mode)"
    print(
        f"CIFAR-100 loaded | Train: {len(train_dataset):,} | Val: {val_str} | Test: {len(test_dataset):,}"
    )
    return train_loader, val_loader, test_loader
