def derive() -> dict:
    commit = FROZEN_COMMIT[:7]
    train = apply_subs(
        frozen_source("experiments/train_baseline.py"), TRAIN_SUBS, "train_controlled"
    )
    data = DATA_HEADER.format(commit=commit) + apply_subs(
        extract_functions(frozen_source("data/datasets.py"), ["get_cifar100_loaders"]),
        DATA_SUBS,
        "data_controlled",
    )
    entropy = ENTROPY_HEADER.format(commit=commit) + apply_subs(
        extract_functions(
            frozen_source("experiments/compute_entropy.py"),
            ["build_raw_train_subset", "build_raw_entropy_loader"],
        ),
        ENTROPY_SUBS,
        "entropy_controlled",
    )
    return {
        "train_controlled.py": train,
        "data_controlled.py": data,
        "entropy_controlled.py": entropy,
    }


def verify() -> dict:
    """{file: True/False} — on-disk copy equals a fresh derivation from the frozen originals."""
    return {
        name: (HERE / name).exists() and (HERE / name).read_text() == text
        for name, text in derive().items()
    }


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--write", action="store_true")
    a = p.parse_args()
    if a.write:
        for name, text in derive().items():
            (HERE / name).write_text(text)
            print(f"wrote {name}")
    res = verify()
    print(res)
    sys.exit(0 if all(res.values()) else 1)
