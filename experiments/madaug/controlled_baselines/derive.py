def frozen_source(path: str) -> str:
    return subprocess.check_output(
        ["git", "show", f"{FROZEN_COMMIT}:{path}"], cwd=PROJECT_ROOT, text=True
    )


def apply_subs(text: str, subs, label: str) -> str:
    for old, new, reason in subs:
        n = text.count(old)
        if n != 1:
            raise AssertionError(
                f"{label}: substitution anchor found {n}x (expected 1): {reason}"
            )
        text = text.replace(old, new)
    return text


def extract_functions(source: str, names) -> str:
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source)
    chunks = []
    for name in names:
        node = next(
            n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == name
        )
        chunks.append("".join(lines[node.lineno - 1 : node.end_lineno]))
    return "\n\n".join(chunks)


